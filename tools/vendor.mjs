// Copies pinned third-party assets from node_modules into public/vendor so the site has no runtime CDN dependency.
// Run: npm run vendor
import { cpSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const nm = root + 'node_modules/';
const out = root + 'public/vendor/';

rmSync(out + 'fonts', { recursive: true, force: true });
rmSync(out + 'fontawesome', { recursive: true, force: true });
mkdirSync(out + 'fonts', { recursive: true });
mkdirSync(out + 'fontawesome/css', { recursive: true });

cpSync(nm + 'three/build/three.min.js', out + 'three.min.js');
cpSync(nm + 'qrcode-generator/qrcode.js', out + 'qrcode.js');

// Font Awesome: css + woff2 only (ttf fallbacks dropped from CSS below)
cpSync(nm + '@fortawesome/fontawesome-free/css/all.min.css', out + 'fontawesome/css/all.min.css');
mkdirSync(out + 'fontawesome/webfonts', { recursive: true });
for (const f of ['fa-solid-900', 'fa-regular-400', 'fa-brands-400', 'fa-v4compatibility']) {
    cpSync(`${nm}@fortawesome/fontawesome-free/webfonts/${f}.woff2`, `${out}fontawesome/webfonts/${f}.woff2`);
}
const faCss = readFileSync(out + 'fontawesome/css/all.min.css', 'utf8').replace(/,url\([^)]*\.ttf\) format\("truetype"\)/g, '');
writeFileSync(out + 'fontawesome/css/all.min.css', faCss);

// Thai + latin subsets of Prompt / Sarabun, weights used by the UI
const FAMILIES = { prompt: [300, 400, 500, 600, 700, 800], sarabun: [300, 400, 500, 600, 700] };
const SUBSETS = ['thai', 'latin'];
let css = '/* generated by tools/vendor.mjs */\n';
for (const [fam, weights] of Object.entries(FAMILIES)) {
    for (const w of weights) {
        const src = readFileSync(`${nm}@fontsource/${fam}/${w}.css`, 'utf8');
        for (const block of src.split('/*').slice(1)) {
            // block header looks like "sarabun-thai-400-normal"
            const m = block.slice(0, block.indexOf('*/')).trim().match(/^[a-z]+-(.+)-\d+-normal$/);
            const subset = m ? m[1] : '';           // 'thai', 'latin', 'latin-ext', ...
            if (!SUBSETS.includes(subset)) continue;
            const file = `${fam}-${subset}-${w}-normal.woff2`;
            cpSync(`${nm}@fontsource/${fam}/files/${file}`, `${out}fonts/${file}`);
            const range = (block.match(/unicode-range:[^;]+;/) || [''])[0];
            const name = fam[0].toUpperCase() + fam.slice(1);
            css += `@font-face{font-family:'${name}';font-style:normal;font-display:swap;font-weight:${w};src:url(./fonts/${file}) format('woff2');${range}}\n`;
        }
    }
}
writeFileSync(out + 'fonts.css', css);
console.log('vendor ok');
