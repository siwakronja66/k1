// One-off/regenerable: builds db/seed.sql + public/data/snapshot.json from the data block
// at the top of public/js/app.js (BUILDINGS_META, ROOMS_DB). Run: node tools/extract-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(root + 'public/js/app.js', 'utf8');
const end = src.indexOf('// 2. THREE.JS SCENE GLOBALS');
if (end < 0) throw new Error('data block marker not found in app.js');

const ctx = { THREE: { Vector3: class { constructor(x, y, z) { Object.assign(this, { x, y, z }); } } } };
vm.runInNewContext(src.slice(0, end) + '\n;this.B = BUILDINGS_META; this.R = ROOMS_DB;', ctx);
const buildings = Object.values(ctx.B);
const rooms = ctx.R;

// Starter "what do you need" keywords -> room whose department handles it.
const SERVICES = [
    ['ขออนุญาตผลิตภัณฑ์สุขภาพ / อย.', 'R411'], ['ต่อใบอนุญาตร้านยา', 'R411'], ['ขออนุญาตเปิดคลินิก', 'R411'],
    ['สถานประกอบการเพื่อสุขภาพ / สปา / นวด', 'R411'], ['ร้องเรียนผลิตภัณฑ์ / โฆษณา', 'R411'],
    ['บัตรทอง / สิทธิ 30 บาท', 'R412'], ['ทำฟัน / ทันตสาธารณสุข', 'R412'],
    ['ส่งหนังสือราชการ', 'R211'], ['สอบถามข้อมูลทั่วไป / ร้องเรียน', 'R211'],
    ['เบิกจ่าย / การเงิน', 'R212'], ['จัดซื้อจัดจ้าง / พัสดุ', 'R213'],
    ['วัคซีน / โรคระบาด', 'R422'], ['เบาหวาน ความดัน / สุขภาพจิต / ยาเสพติด', 'R423'],
    ['แม่และเด็ก / ผู้สูงอายุ', 'R421'], ['สมัครงาน / บุคลากร HR', 'R433'],
    ['นวดแผนไทย / สมุนไพร', 'RTTM1'], ['ขยะติดเชื้อ / สุขาภิบาลอาหาร', 'R442'],
    ['ประชุม / ห้องประชุมใหญ่', 'R443'], ['พบนายแพทย์สาธารณสุขจังหวัด', 'R432'],
];

const q = v => v === null || v === undefined ? 'NULL'
    : typeof v === 'number' ? String(v)
    : "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";

const out = ['-- GENERATED by tools/extract-seed.mjs — edit data in admin UI after first load, not here.', 'SET NAMES utf8mb4;', ''];
buildings.forEach((b, i) => out.push(
    `INSERT INTO buildings (id,name,short_name,floors,width,depth,sort_order) VALUES (${[b.id, b.name, b.shortName, b.floors, b.width, b.depth, i].map(q).join(',')});`));
out.push('');
rooms.forEach((r, i) => {
    out.push(`INSERT INTO rooms (id,building_id,floor,room_no,label,lx,lz,w,d) VALUES (${[r.id, r.building, r.floor, r.roomNo, r.name, r.lx, r.lz, r.w, r.d].map(q).join(',')});`);
    out.push(`INSERT INTO departments (id,name,head_title,phone_ext,description,type) VALUES (${[i + 1, r.name, r.head, r.phone, r.desc, r.type].map(q).join(',')});`);
    out.push(`INSERT INTO room_assignments (room_id,department_id,valid_from) VALUES (${q(r.id)},${i + 1},'2026-01-01');`);
});
out.push('');
const deptIdByRoom = Object.fromEntries(rooms.map((r, i) => [r.id, i + 1]));
SERVICES.forEach(([kw, roomId]) => {
    if (!deptIdByRoom[roomId]) throw new Error('unknown room in SERVICES: ' + roomId);
    out.push(`INSERT INTO services (keyword,department_id) VALUES (${q(kw)},${deptIdByRoom[roomId]});`);
});
writeFileSync(root + 'db/seed.sql', out.join('\n') + '\n');

// Nav graph from db/nav-seed.sql (single source of truth for both DB and static fallback)
const navSql = readFileSync(root + 'db/nav-seed.sql', 'utf8');
const nodeRe = /\('(\w+)',\s*(NULL|'(\w+)'),\s*(\d),\s*(-?[\d.]+),\s*(-?[\d.]+),\s*(-?[\d.]+),\s*'(\w+)',\s*'([^']*)'\)/g;
const nodes = [...navSql.matchAll(nodeRe)].map(m => ({
    id: m[1], buildingId: m[3] ?? null, floor: +m[4], x: +m[5], y: +m[6], z: +m[7], kind: m[8], label: m[9],
}));
const nodeIds = new Set(nodes.map(n => n.id));
const edges = [...navSql.matchAll(/\('(\w+)',\s*'(\w+)',\s*([01])\)/g)].map(m => ({ a: m[1], b: m[2], accessible: m[3] === '1' }));
edges.forEach(e => { if (!nodeIds.has(e.a) || !nodeIds.has(e.b)) throw new Error(`edge ${e.a}-${e.b} references unknown node`); });

// Static fallback served when the API is unreachable (same shape as GET /api/v1/snapshot).
const snapshot = {
    version: 0,
    buildings: buildings.map(b => ({ id: b.id, name: b.name, shortName: b.shortName, floors: b.floors })),
    rooms: rooms.map(r => ({ id: r.id, building: r.building, floor: r.floor, roomNo: r.roomNo, name: r.name, head: r.head, phone: r.phone, type: r.type, desc: r.desc, lx: r.lx, lz: r.lz, w: r.w, d: r.d })),
    services: SERVICES.map(([keyword, roomId]) => ({ keyword, roomId })),
    nav: { nodes, edges },
};
writeFileSync(root + 'public/data/snapshot.json', JSON.stringify(snapshot, null, 1) + '\n');
console.log(`buildings=${buildings.length} rooms=${rooms.length} services=${SERVICES.length} nav=${nodes.length}/${edges.length}`);
